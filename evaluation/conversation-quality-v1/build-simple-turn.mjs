import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {createSimpleTurnVariant} from './simple-turn-variant.mjs';
const baseline=fs.readFileSync(new URL('./group-luna-summary-v1.project.json',import.meta.url));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
assert.equal(sha(baseline),'0f6247929215fdb20f470db6122ebc23fde1bd863a436e2019a78669b3eb385e','Baseline changed: reevaluation required');
const clause=fs.readFileSync(new URL('./clauses/group-simple-turn-v1.txt',import.meta.url),'utf8');
const candidate=JSON.stringify(createSimpleTurnVariant(JSON.parse(baseline),clause),null,2)+'\n';
assert.equal(sha(candidate),'0d104f3c1b3412475d6995f0aafe0ae649bcb0d11f37d17fc366a8d1b5a8544b','Candidate differs from evaluated composition');
const output=new URL('./group-simple-turn-v1.project.json',import.meta.url);
if(fs.existsSync(output))assert.equal(fs.readFileSync(output,'utf8'),candidate,'Refusing to overwrite another artifact');
else fs.writeFileSync(output,candidate,{flag:'wx'});
console.log('Local experimental artifact verified; no activation: '+sha(candidate));
